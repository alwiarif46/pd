// Generates src/styles/ui-preflight.css: Tailwind's preflight, applied everywhere except inside the
// legacy `.app-shell`. Run after a Tailwind upgrade: node apps/web/scripts/scope-preflight.mjs
// Uses postcss, which Vite already installs.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const postcss = require('postcss');
const source = readFileSync(require.resolve('tailwindcss/preflight.css'), 'utf8');
const version = require('tailwindcss/package.json').version;

// Zero specificity, so the reset keeps preflight's own specificity.
const OUTSIDE_LEGACY = ':where(:not(.app-shell, .app-shell *))';
// html and body sit outside .app-shell; resetting them would change the legacy pages.
const SKIP = new Set(['html', ':host', 'body']);

function scope(selector) {
  const s = selector.trim();
  if (SKIP.has(s)) return null;
  const at = s.indexOf('::');
  const base = at === -1 ? s : s.slice(0, at);
  const pseudo = at === -1 ? '' : s.slice(at);
  return `${base ? `:where(${base})` : ''}${OUTSIDE_LEGACY}${pseudo}`;
}

const root = postcss.parse(source);
root.walkRules((rule) => {
  const scoped = rule.selectors.map(scope).filter(Boolean);
  if (scoped.length === 0) rule.remove();
  else rule.selectors = scoped;
});
root.walkComments((comment) => comment.remove());

const header = `/* Generated by apps/web/scripts/scope-preflight.mjs from tailwindcss@${version} preflight.css. Do not edit.
   Preflight for new screens only: every selector is limited to elements outside the legacy .app-shell,
   so src/screens and src/components/*.tsx keep their current look. Remove this file and turn on the real
   preflight when the legacy screens are retired. */\n`;
const out = fileURLToPath(new URL('../src/styles/ui-preflight.css', import.meta.url));
writeFileSync(out, header + root.toString().replace(/\n{3,}/g, '\n\n'));
console.log('wrote', out);
