-- 0005_documents_and_bids
-- - documents.marking_page: the lowest page a marking was found on (the marking step writes it).
-- - documents.live_status gains 'restore_requested' (text, no type change). The api used to set
--   'restoring' straight away on a restore request, whether or not an archive copy existed:
--   - with a usable archive copy (not purged, not expired) and none already restoring or
--     restored: the document becomes 'restore_requested' and its usable copies 'requested',
--     as the api now does;
--   - with no usable copy: there is nothing to restore, so it goes back to 'archived'.
-- - bids.status takes four values (09 s5.2): planning, writing, submitted, closed. Old rows
--   ('draft', or anything else the api wrote before) become 'planning'; new rows default to
--   'planning'; a CHECK constraint holds it.
-- Lock order: documents and archive_objects first, bids last, as the api locks them (credits.ts),
-- because deploys migrate while the old api is still serving. lock_timeout makes a migration
-- that waits on a busy table fail fast and roll back instead of queueing every request behind
-- it; it is reset at the end, since the migrator runs all pending migrations in one transaction.
-- The owner sees no tenant rows while FORCE ROW LEVEL SECURITY is on (0001), so it is lifted on
-- documents, archive_objects, and bids for the updates and put back.
-- Generated by drizzle-kit (ADD COLUMN marking_page and SET DEFAULT 'planning', moved into
-- lock order); the rest is hand-written.
