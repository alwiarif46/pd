-- Expiry times are stored as UTC wall-clock times (timestamp without time zone).
WITH "usable" AS (
  SELECT "a"."id", "a"."document_id", "a"."restore_status" FROM "archive_objects" "a"
  WHERE "a"."purged_at" IS NULL
    AND ("a"."expires_at" IS NULL OR "a"."expires_at" > (now() AT TIME ZONE 'UTC'))
),
"target" AS (
  SELECT "d"."id", "d"."updated_at" FROM "documents" "d"
  WHERE "d"."live_status" = 'restoring'
    AND EXISTS (SELECT 1 FROM "usable" "u" WHERE "u"."document_id" = "d"."id")
    AND NOT EXISTS (
      SELECT 1 FROM "usable" "u"
      WHERE "u"."document_id" = "d"."id" AND "u"."restore_status" IN ('restoring', 'restored')
    )
),
"moved" AS (
  UPDATE "documents" SET "live_status" = 'restore_requested', "updated_at" = now()
  FROM "target" WHERE "documents"."id" = "target"."id"
  RETURNING "documents"."id", "target"."updated_at" AS "requested_at"
)
UPDATE "archive_objects" SET
  "restore_status" = 'requested',
  "restore_requested_at" = coalesce("archive_objects"."restore_requested_at", "moved"."requested_at"),
  "updated_at" = now()
FROM "moved", "usable"
WHERE "archive_objects"."document_id" = "moved"."id"
  AND "usable"."id" = "archive_objects"."id"
  AND ("archive_objects"."restore_status" IS NULL OR "archive_objects"."restore_status" = 'none');
