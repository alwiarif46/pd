--   The owner sees no tenant rows while FORCE ROW LEVEL SECURITY is on (0001), so it is lifted on
--   organizations for the backfill and put back, as 0004 does for bids.
-- - One organization per Stripe customer (unique index; NULLs stay distinct, so organizations
--   without a customer are not constrained).
-- Generated by drizzle-kit (the index); the backfill and the CHECK are hand-written.
