UPDATE "outline_items" AS o SET "position" = ranked.rn - 1
FROM (
  SELECT "id", row_number() OVER (
    PARTITION BY "bid_id", "parent_id"
    ORDER BY
      coalesce("number" ~ '^[0-9]{1,9}(\.[0-9]{1,9})*$', false) DESC,
      CASE WHEN "number" ~ '^[0-9]{1,9}(\.[0-9]{1,9})*$' THEN string_to_array("number", '.')::int[] END,
      "number",
      "created_at",
      "id"
  ) AS rn
  FROM "outline_items"
) AS ranked
WHERE o."id" = ranked."id" AND o."position" IS DISTINCT FROM ranked.rn - 1;
