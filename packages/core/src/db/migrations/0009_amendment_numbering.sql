-- 0009_amendment_numbering
-- Amendment numbers (04 s3.1, 03 s2) and the columns the amendment run needs.
-- - documents.amendment_no_source ('user' | 'document' | 'sequence'; null for other kinds) and
--   documents.amendment_no_found (the number read from the file). amendment_no is 1 to 999, and
--   unique among the bid's amendments that are not deleted (documents_bid_amendment_no_uq, a
--   backstop: the worker and the api check the full rule, under the bid lock, which also keeps
--   the number of a deleted amendment that wrote rows).
-- - upload_sessions.amendment_no: the number typed at upload (1 to 999).
-- - amendments.amendment_no mirrors documents.amendment_no and may be null (not settled yet);
--   amendments.status gains 'needs_number' and 'failed'.
-- - amendment_links.source_page and source_quote: the amendment text behind a supersede or a
--   withdraw; indexes on amendment_id, old_row_id and new_row_id.
-- - compliance_rows (bid_id, req_id) index for req_id allocation.
-- - app_settings amendment_link_confidence = 0.80 (kept when already set).
-- Backfill: amendment documents of each bid are numbered by created_at (source 'sequence'): every
-- one that is not deleted, and every deleted one whose amendment wrote rows (needs_confirmation or
-- applied), since that number stays taken. Numbers above 999 stay null. The number is mirrored to
-- amendments, and compliance_rows.changed_by_amendment is set from the auto or confirmed
-- supersede and withdraw links (the latest link per row). No amendment wrote added rows before
-- this, so compliance_rows.amendment_no needs no backfill.
-- The owner sees no tenant rows while FORCE ROW LEVEL SECURITY is on (0001), so it is lifted on
-- the four tables the backfill reads or writes and put back, as 0004, 0007 and 0008 do.
-- lock_timeout: as in 0007 and 0008, set here and reset at the end (the migrator runs every
-- pending migration in one transaction).
-- Generated by drizzle-kit (the columns, the NOT NULL drop and the indexes); the backfill, the
-- CHECKs, the setting and lock_timeout are hand-written.
