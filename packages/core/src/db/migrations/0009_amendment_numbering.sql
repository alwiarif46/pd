UPDATE "compliance_rows" AS r SET "changed_by_amendment" = latest."amendment_no"
FROM (
  SELECT DISTINCT ON (l."old_row_id") l."old_row_id", a."amendment_no", a."bid_id"
  FROM "amendment_links" AS l
  JOIN "amendments" AS a ON a."id" = l."amendment_id"
  WHERE l."row_table" = 'compliance_rows'
    AND l."old_row_id" IS NOT NULL
    AND l."action" IN ('supersede', 'withdraw')
    AND l."status" IN ('auto', 'confirmed')
    AND a."amendment_no" IS NOT NULL
  ORDER BY l."old_row_id", l."created_at" DESC, l."id" DESC
) AS latest
WHERE r."id" = latest."old_row_id"
  AND r."bid_id" = latest."bid_id"
  AND r."changed_by_amendment" IS NULL
  AND r."supersede_status" IN ('superseded', 'withdrawn');
