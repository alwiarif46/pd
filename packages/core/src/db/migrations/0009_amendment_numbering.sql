WITH numbered AS (
  SELECT d."id", row_number() OVER (PARTITION BY d."bid_id" ORDER BY d."created_at", d."id") AS rn
  FROM "documents" AS d
  WHERE d."kind" = 'amendment'
    AND (
      d."live_status" IS DISTINCT FROM 'deleted'
      OR EXISTS (
        SELECT 1 FROM "amendments" AS a
        WHERE a."document_id" = d."id" AND a."status" IN ('needs_confirmation', 'applied')
      )
    )
)
UPDATE "documents" AS d SET
  "amendment_no" = CASE WHEN numbered.rn <= 999 THEN numbered.rn END,
  "amendment_no_source" = CASE WHEN numbered.rn <= 999 THEN 'sequence' END
FROM numbered
WHERE d."id" = numbered."id";
