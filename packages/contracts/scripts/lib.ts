import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import { compile, type JSONSchema } from 'json-schema-to-typescript';
import { parse as parseYaml } from 'yaml';
import { PACKAGE_ROOT, SERVICES, eventNames, loadEnvelopeSchema, loadEventSchema } from '../src/index';

export const BANNER = '// Generated by scripts/generate.ts from the contract files. Do not edit by hand.\n';

export function openapiPath(id: string): string {
  return join(PACKAGE_ROOT, 'openapi', `${id}.yaml`);
}

function interfaceName(name: string): string {
  return (
    name
      .split(/[._]/)
      .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
      .join('') + 'Event'
  );
}

/** Merge the shared envelope into one event schema so the generator needs no cross-file refs. */
function flatten(name: string): JSONSchema {
  const envelope = loadEnvelopeSchema() as unknown as {
    required: string[];
    properties: Record<string, object>;
  };
  const event = loadEventSchema(name) as unknown as { properties: Record<string, object> };
  const properties: Record<string, object> = { ...envelope.properties };
  for (const [key, value] of Object.entries(event.properties)) {
    properties[key] = { ...(properties[key] ?? {}), ...value };
  }
  return {
    type: 'object',
    description: `Event ${name}.`,
    required: envelope.required,
    properties,
  } as JSONSchema;
}

/** Everything the generator writes, keyed by path relative to the package root. */
export async function buildGenerated(): Promise<Map<string, string>> {
  const out = new Map<string, string>();
  for (const svc of SERVICES) {
    const doc = parseYaml(readFileSync(openapiPath(svc.id), 'utf8')) as Record<string, unknown>;
    const ast = await openapiTS(doc as never);
    out.set(`generated/openapi/${svc.id}.d.ts`, BANNER + astToString(ast));
  }
  const parts: string[] = [BANNER];
  for (const name of eventNames) {
    parts.push(await compile(flatten(name), interfaceName(name), { bannerComment: '', additionalProperties: false }));
  }
  out.set('generated/events.d.ts', parts.join('\n'));
  return out;
}

export function listFiles(dir: string, suffix: string): string[] {
  return readdirSync(dir).filter((f) => f.endsWith(suffix)).sort();
}
